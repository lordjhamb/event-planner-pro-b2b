drop table if exists inventory_transactions cascade;
drop table if exists inventory_items cascade;
drop table if exists messages cascade;
drop table if exists tasks cascade;
drop table if exists events cascade;
drop table if exists weddings cascade;
drop table if exists wedding_templates cascade;
drop table if exists vendors cascade;
drop table if exists workers cascade;
drop table if exists invitations cascade;
drop table if exists profiles cascade;
drop table if exists organizations cascade;

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- 1. ORGANIZATIONS (New Core Entity)
create table organizations (
  id uuid default uuid_generate_v4() primary key,
  name text not null,
  plan text default 'free',
  code text unique, -- Unique 6-char code for joining
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. PROFILES (Extends Supabase Auth)
create table profiles (
  id uuid references auth.users on delete cascade not null primary key,
  email text,
  full_name text,
  role text check (role in ('owner', 'lead', 'worker')) default 'worker',
  organization_id uuid references organizations(id),
  avatar_url text,
  phone text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. INVITATIONS (For Email & WhatsApp Onboarding)
create table invitations (
  id uuid default uuid_generate_v4() primary key,
  email text, -- Nullable if invited via Phone
  phone text, -- Nullable if invited via Email
  role text not null check (role in ('owner', 'lead', 'worker')),
  organization_id uuid references organizations(id) not null,
  invited_by uuid references auth.users(id),
  token text unique not null,
  status text default 'pending', -- pending, accepted, expired
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. WORKERS (The "Roster" view of team members)
create table workers (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id),    -- Multi-tenant link
  profile_id uuid references profiles(id) on delete cascade,              -- Link to actual user if they signed up
  name text not null,
  role text not null, -- Display role (e.g. "Senior Florist"), distinct from system role
  email text,
  phone text,
  available boolean default true,
  skills text[],
  rating numeric,
  "joinDate" date
);

-- 5. VENDORS
create table vendors (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id),
  name text not null,
  category text,
  rating numeric,
  status text check (status in ('Confirmed', 'Pending', 'Rejected')),
  phone text,
  email text,
  location text,
  pricing text,
  services text[]
);

-- 6. WEDDINGS
create table weddings (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id),
  name text not null,
  "clientName" text not null,
  "brideName" text,
  "groomName" text,
  "weddingType" text,
  "totalBudget" numeric default 0,
  "startDate" timestamp with time zone,
  "endDate" timestamp with time zone,
  status text check (status in ('Active', 'Upcoming', 'Completed', 'Cancelled')) default 'Active',
  created_at timestamp with time zone default now()
);

-- 7. EVENTS
create table events (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id),
  "weddingId" bigint references weddings(id) on delete cascade,
  name text not null, 
  type text, 
  dates text,
  "startDate" timestamp with time zone,
  "startTime" time,
  "endTime" time,
  status text check (status in ('Active', 'Upcoming', 'Completed')),
  location text,
  venue text,
  "venueAddress" text,
  budget numeric default 0,
  spent numeric default 0,
  progress integer default 0,
  description text,
  "primaryLeadId" bigint references workers(id),
  "departmentLeads" jsonb,
  attendance integer,
  workers bigint[]
);

-- 8. TASKS
create table tasks (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id),
  "weddingId" bigint references weddings(id) on delete cascade,
  "eventId" bigint references events(id) on delete cascade,
  title text not null,
  description text,
  status text check (status in ('Open', 'In Progress', 'Submitted', 'Approved', 'Completed', 'Blocked')),
  priority text check (priority in ('High', 'Medium', 'Normal')),
  "dueDate" text,
  assignee bigint references workers(id),
  budget numeric,
  spent numeric,
  "submittedBy" bigint references workers(id),
  department text,
  "vendorId" bigint references vendors(id),
  "requiresOwnerApproval" boolean default false,
  "approverId" bigint references workers(id),
  "rejectionNote" text,
  "helpNote" text,
  "checklistDone" integer default 0,
  "checklistTotal" integer default 0,
  checklist jsonb
);

-- 9. MESSAGES
create table messages (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id),
  "weddingId" bigint references weddings(id) on delete cascade,
  "eventId" bigint references events(id) on delete cascade,
  "senderId" text,
  text text,
  "isSystem" boolean default false,
  timestamp timestamp with time zone default now()
);

-- 10. TEMPLATES
create table wedding_templates (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id), -- Null means global template
  name text not null,
  description text,
  default_events jsonb
);

-- 11. INVENTORY
create table inventory_items (
  id uuid default uuid_generate_v4() primary key,
  organization_id uuid references organizations(id),
  name text not null,
  category text,
  "totalQuantity" integer default 0,
  "availableQuantity" integer default 0,
  "pricePerUnit" numeric default 0,
  "imageUrl" text,
  description text
);

create table inventory_transactions (
  id uuid default uuid_generate_v4() primary key,
  organization_id uuid references organizations(id),
  "itemId" uuid references inventory_items(id),
  "eventId" bigint references events(id),
  "taskId" bigint references tasks(id),
  type text check (type in ('Check-In', 'Check-Out', 'Maintenance', 'Purchase', 'Loss')),
  quantity integer not null,
  timestamp timestamp with time zone default now(),
  notes text,
  "performedBy" uuid references auth.users(id)
);

-- 12. FINANCE
create table finance_transactions (
  id uuid default uuid_generate_v4() primary key,
  organization_id uuid references organizations(id),
  "eventId" bigint references events(id),
  type text check (type in ('Income', 'Expense')),
  category text,
  amount numeric not null,
  mode text,
  status text check (status in ('Paid', 'Pending', 'Overdue')),
  date timestamp with time zone default now(),
  notes text,
  "recordedBy" uuid references auth.users(id)
);

create table task_inventory_requests (
  id uuid default uuid_generate_v4() primary key,
  organization_id uuid references organizations(id),
  "taskId" bigint references tasks(id),
  "itemId" uuid references inventory_items(id),
  quantity integer not null,
  status text check (status in ('Requested', 'Approved', 'Rejected', 'Used', 'Returned')),
  "requestedBy" uuid references auth.users(id),
  "approvedBy" uuid references auth.users(id),
  createdAt timestamp with time zone default now()
);


-- 13. NOTIFICATIONS
create table notifications (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id),
  "recipientId" uuid references auth.users(id),
  "senderId" uuid references auth.users(id),
  title text,
  message text,
  type text, -- 'task', 'info', 'alert', 'chat'
  link text,
  read boolean default false,
  created_at timestamp with time zone default now()
);

